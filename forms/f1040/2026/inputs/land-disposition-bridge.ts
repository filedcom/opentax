import { z } from "zod";
import {
  calculateLandDispositions2026,
  landDispositionSource2026Schema,
  section1231FinalizedLoss2026Schema,
} from "./land-disposition-source.ts";
import { investmentOwner2026 } from "./investment-source.ts";

const ref = z.string().trim().min(1);
/** Internal handoff from the future disposition/loss-limitation owner. Never a
 * public claim: the loss amount must be supplied by that calculation owner. */
export const landDispositionBridge2026Schema = z.object({
  source: landDispositionSource2026Schema,
  finalized_loss: section1231FinalizedLoss2026Schema.optional(),
  reconciliation: z.object({
    record_reference: ref,
    capital_inventory_reference: ref,
    regular_and_amt_basis_and_history_identical: z.literal(true),
  }).strict(),
  niit_review: z.object({
    record_reference: ref,
    no_prior_niit_capital_loss_carryover_adjustment: z.literal(true),
    activities: z.array(
      z.object({
        activity_reference: ref,
        owner_tin: z.string().regex(/^\d{9}$/),
        business_name: ref,
        record_reference: ref,
        section162_trade_or_business: z.literal(true),
        nonpassive_throughout_property_ownership: z.literal(true),
        participation_history_reference: ref,
        not_trading_financial_instruments_or_commodities: z.literal(true),
        no_former_passive_or_suspended_loss_adjustments: z.literal(true),
      }).strict(),
    ).min(1),
  }).strict().optional(),
}).strict();
export type LandDispositionBridge2026 = z.input<
  typeof landDispositionBridge2026Schema
>;

export function resolveLandDispositionBridge2026(
  raw: LandDispositionBridge2026,
  ownerRaw: z.input<typeof investmentOwner2026>,
  capitalInventoryReference: string | undefined,
  landInventoryReference: string | undefined,
) {
  const bridge = landDispositionBridge2026Schema.parse(raw);
  const owner = investmentOwner2026.parse(ownerRaw);
  const source = bridge.source;
  if (
    source.filing_status !== owner.filing_status ||
    source.taxpayer_ssn !== owner.taxpayer_ssn ||
    source.spouse_ssn !== owner.spouse_ssn
  ) {
    throw new Error(
      "Land and capital sources must have the same return owners",
    );
  }
  if (
    bridge.reconciliation.capital_inventory_reference !==
      capitalInventoryReference ||
    source.claim.record_reference !== landInventoryReference
  ) {
    throw new Error(
      "Land and capital inventories require matching reciprocal source references",
    );
  }
  const calculation = calculateLandDispositions2026(
    source,
    bridge.finalized_loss,
  );
  return { source_input: bridge, calculation };
}

/** Form 8960 instructions, lines 5a-5d worksheet: exclude the source gain,
 * not a Schedule D recalculation with a second $3,000 capital-loss limit. */
export function landNiitExclusion2026(
  resolved: ReturnType<typeof resolveLandDispositionBridge2026>,
) {
  const review = resolved.source_input.niit_review;
  if (!review) {
    throw new Error(
      "Land NIIT needs reviewed activity and participation history",
    );
  }
  const { calculation: land } = resolved;
  const key = (activity: string, owner: string) => `${owner}:${activity}`;
  const expected = new Set(
    land.rows.map((r) => key(r.source.activity_reference, r.source.owner_tin)),
  );
  const supplied = review.activities.map((a) =>
    key(a.activity_reference, a.owner_tin)
  );
  if (
    new Set(supplied).size !== supplied.length ||
    supplied.length !== expected.size ||
    supplied.some((k) => !expected.has(k))
  ) {
    throw new Error(
      "Land NIIT reviews must identify every owner/activity once",
    );
  }
  const capital = land.line10_long_term_gain;
  const ordinary = land.line20b_schedule1_gain_loss;
  return {
    review,
    activities: review.activities.map((activity) => ({
      ...activity,
      sale_references: land.rows.filter((r) =>
        key(r.source.activity_reference, r.source.owner_tin) ===
          key(activity.activity_reference, activity.owner_tin)
      ).map((r) => r.source.sale_reference),
    })),
    excluded_capital_gain: capital,
    excluded_ordinary_gain_loss: ordinary,
    worksheet_capital_adjustment: -capital,
    worksheet_ordinary_adjustment: -ordinary,
    // This source has no excluded *capital loss*: a net section 1231 loss is
    // ordinary. No line 2(i) adjustment is generated by these dispositions.
    next_year_excluded_capital_loss_adjustment: 0,
    line5b_adjustment: -capital - ordinary,
  };
}
