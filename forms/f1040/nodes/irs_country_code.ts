export function isTy2025IrsCountryCode(value: string): boolean {
  return TY2025_IRS_COUNTRY_CODES.has(value);
}

export const ty2025IrsCountryCodeSchema = z.string().regex(/^[A-Z]{2}$/)
  .refine(
    isTy2025IrsCountryCode,
    "TY2025 Form 1116 requires an IRS MeF country code (Germany is GM, not ISO DE)",
  );

export function assertTy2025IrsCountryCode(value: string): void {
  if (!isTy2025IrsCountryCode(value)) {
    throw new Error(
      `Form 1116 requires a TY2025 IRS MeF country code; received ${value} (Germany is GM, not ISO DE)`,
    );
  }
}
