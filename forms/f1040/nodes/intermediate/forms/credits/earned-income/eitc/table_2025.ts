// The IRS table footnotes split these last $50 bands at the exact dollar.
const TERMINAL_BANDS: Record<number, [number, number, number]> = {
  382: [0, 19_104, 1],
  524: [4, 26_214, 1],
  1008: [1, 50_434, 3],
  1146: [2, 57_310, 1],
  1151: [5, 57_554, 0],
  1231: [3, 61_555, 1],
  1288: [6, 64_430, 3],
  1373: [7, 68_675, 3],
};

/** IRS EIC table lookup for a TY2025 whole-dollar worksheet amount. */
export function lookupEic2025(
  amount: number,
  children: number,
  joint: boolean,
): number {
  if (amount < 1 || amount >= 68_700) return 0;
  const column = Math.min(children, 3) + (joint ? 4 : 0);
  const band = Math.floor(amount / 50);
  const split = TERMINAL_BANDS[band];
  if (split && split[0] === column) return amount < split[1] ? split[2] : 0;
  return CREDIT_BY_INCOME_BAND[band]?.[column] ?? 0;
}
